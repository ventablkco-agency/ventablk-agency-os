"use client";

import { useState } from "react";
import { importRepositoryInventory } from "./actions";

type ClientOption = { id: string; name: string; organization: string | null };
type ExistingProject = { sourceId: string | null; repositoryUrl: string | null; clientId: string; name: string };

type RepositoryRecord = {
  sourceId: string;
  directory: string;
  repositoryUrl: string | null;
  branch: string | null;
  commit: string | null;
  name: string;
  packageName: string | null;
  framework: string;
  hostingSignals: string[];
  ciSignals: string[];
  client: { name: string | null; organization: string | null } | null;
  explicitProjectMetadata: { name: string | null; websiteUrl: string | null; hosting: string | null; status: string | null } | null;
  needsClientMapping: boolean;
};

type Inventory = {
  schemaVersion: number;
  generatedAt: string;
  scanRoot: string;
  summary?: { repositoriesFound?: number; repositoriesNeedingClientMapping?: number; scanErrors?: number };
  repositories: RepositoryRecord[];
  errors?: Array<{ path: string; message: string }>;
};

function normalizedUrl(value: string | null) {
  return (value || "").trim().replace(/\.git$/i, "").replace(/\/+$/, "").toLowerCase();
}
function likelySameClient(left: RepositoryRecord["client"], right: ClientOption) {
  return Boolean(left && ((left.organization && right.organization && left.organization.toLowerCase() === right.organization.toLowerCase()) ||
    (left.name && right.name && left.name.toLowerCase() === right.name.toLowerCase())));
}

export default function BulkImportForm({ clients, projects }: { clients: ClientOption[]; projects: ExistingProject[] }) {
  const [inventory, setInventory] = useState<Inventory | null>(null);
  const [mappings, setMappings] = useState<Record<string, string>>({});
  const [fileName, setFileName] = useState("");
  const [error, setError] = useState("");

  async function selectFile(file?: File) {
    setInventory(null);
    setMappings({});
    setFileName(file?.name || "");
    setError("");
    if (!file) return;
    if (file.size > 800_000) {
      setError("Keep the inventory under 800 KB. Exclude archived or unrelated folders and rescan.");
      return;
    }
    try {
      const parsed = JSON.parse(await file.text()) as Inventory;
      if (!parsed || parsed.schemaVersion !== 1 || !Array.isArray(parsed.repositories) || parsed.repositories.length > 250) {
        throw new Error("This is not a supported repository inventory. Select the JSON generated by scripts/repo-scanner.mjs.");
      }
      if (typeof parsed.scanRoot !== "string" || parsed.repositories.some((item) =>
        !item ||
        typeof item.sourceId !== "string" ||
        !item.sourceId.trim() ||
        typeof item.name !== "string" ||
        typeof item.directory !== "string" ||
        typeof item.framework !== "string" ||
        !Array.isArray(item.hostingSignals) ||
        !item.hostingSignals.every((signal) => typeof signal === "string") ||
        !Array.isArray(item.ciSignals) ||
        !item.ciSignals.every((signal) => typeof signal === "string") ||
        (item.repositoryUrl !== null && typeof item.repositoryUrl !== "string")
      )) {
        throw new Error("One or more repository entries are incomplete. Regenerate the inventory.");
      }
      if (new Set(parsed.repositories.map((item) => item.sourceId)).size !== parsed.repositories.length) {
        throw new Error("This inventory repeats a repository identifier. Resolve duplicate entries and rescan.");
      }
      const nextMappings: Record<string, string> = {};
      for (const item of parsed.repositories) {
        const matchingProject = projects.find((p) =>
          (p.sourceId && p.sourceId === item.sourceId) ||
          (p.repositoryUrl && item.repositoryUrl && normalizedUrl(p.repositoryUrl) === normalizedUrl(item.repositoryUrl))
        );
        if (matchingProject) {
          nextMappings[item.sourceId] = matchingProject.clientId;
          continue;
        }
        const matchingClient = clients.find((candidate) => likelySameClient(item.client, candidate));
        if (matchingClient) nextMappings[item.sourceId] = matchingClient.id;
      }
      setInventory(parsed);
      setMappings(nextMappings);
    } catch (problem) {
      setError(problem instanceof Error ? problem.message : "Could not read this inventory file.");
    }
  }

  const allMapped = Boolean(inventory && inventory.repositories.length > 0 &&
    inventory.repositories.every((item) => Boolean(mappings[item.sourceId])));
  const payload = inventory ? JSON.stringify(inventory) : "";

  return (
    <form action={importRepositoryInventory} className="client-form import-form">
      <label className="file-picker">
        Repository inventory JSON
        <input type="file" accept=".json,application/json" required onChange={(event) => void selectFile(event.target.files?.[0])} />
      </label>
      {fileName && <p className="muted-copy">Selected: {fileName}</p>}
      {error && <p className="notice" role="alert">{error}</p>}
      {inventory && (
        <>
          <div className="notice success-notice" role="status">
            Found {inventory.repositories.length} repositories under {inventory.scanRoot}. Review the proposed client mapping for every repository before applying. {inventory.errors?.length ? ` The scan also reported ${inventory.errors.length} folder access errors.` : ""}
          </div>
          {inventory.repositories.length === 0 ? <p className="empty">No Git repositories were found in this inventory.</p> : (
            <div className="bulk-preview-wrap">
              <table className="bulk-preview-table">
                <thead><tr><th>Repository</th><th>Detected stack</th><th>Client mapping</th></tr></thead>
                <tbody>
                  {inventory.repositories.map((item) => {
                    const existing = projects.find((p) =>
                      (p.sourceId && p.sourceId === item.sourceId) ||
                      (p.repositoryUrl && item.repositoryUrl && normalizedUrl(p.repositoryUrl) === normalizedUrl(item.repositoryUrl))
                    );
                    const canCreate = Boolean(item.client?.name || item.client?.organization);
                    return (
                      <tr key={item.sourceId}>
                        <td>
                          <strong>{item.name}</strong>
                          <small>{item.directory}</small>
                          {item.repositoryUrl && <small>{item.repositoryUrl}</small>}
                          {existing && <small className="import-existing">Existing project: {existing.name}</small>}
                        </td>
                        <td>
                          <span>{item.framework}</span>
                          {item.branch && <small>Branch: {item.branch}</small>}
                          {item.commit && <small>Commit: {item.commit}</small>}
                          {item.hostingSignals.map((signal) => <small key={signal}>{signal}</small>)}
                          {item.ciSignals.map((signal) => <small key={signal}>{signal}</small>)}
                        </td>
                        <td>
                          <label className="mapping-select-label">
                            <span className="sr-only">Client for {item.name}</span>
                            <select value={mappings[item.sourceId] || ""} onChange={(event) => setMappings((current) => ({ ...current, [item.sourceId]: event.target.value }))} required>
                              <option value="">Choose a client…</option>
                              {clients.map((client) => <option key={client.id} value={client.id}>{client.organization || client.name}{client.organization ? ` — ${client.name}` : ""}</option>)}
                              {canCreate && <option value="__create__">Create from repository metadata: {item.client?.organization || item.client?.name}</option>}
                            </select>
                          </label>
                          {canCreate && <small>Only the approved name/organization will be imported; no contact or financial data is read.</small>}
                          {!canCreate && !existing && <small>Choose an existing client. This inventory has no confirmed client metadata.</small>}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          )}
          <input type="hidden" name="inventoryJson" value={payload} />
          <input type="hidden" name="mappingsJson" value={JSON.stringify(mappings)} />
          {inventory.repositories.length > 0 && <p className="muted-copy">Existing projects keep their names, status, deadlines and commercial fields. The sync fills missing repository/website/hosting metadata only. A project linked to a different client is skipped and reported as a conflict.</p>}
          <button type="submit" className="primary-button" disabled={!allMapped}>Apply reviewed import ({inventory.repositories.length} repositories)</button>
        </>
      )}
      {!inventory && !error && <p className="muted-copy">Select the JSON inventory generated by the local scanner. The dashboard previews every repository before writing anything; project code is never executed.</p>}
    </form>
  );
}
